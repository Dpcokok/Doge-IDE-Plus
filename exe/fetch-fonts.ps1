# Doge IDE - fetch Google Fonts (Geist + Geist Mono, latin subsets) into web/fonts
# Re-runnable: downloads woff2 files and writes web/fonts/geist.css with local URLs.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not (Test-Path (Join-Path $root 'doge-ide.html'))) { $root = $PSScriptRoot }
$fontsDir = Join-Path $root 'web\fonts'
$vendorDir = Join-Path $fontsDir 'geist'
New-Item -ItemType Directory -Force -Path $vendorDir | Out-Null

$ua = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
$cssUrl = 'https://fonts.googleapis.com/css2?family=Geist+Mono:wght@100..900&family=Geist:wght@100..900&display=swap'
$css = (Invoke-WebRequest -Uri $cssUrl -Headers @{ 'User-Agent' = $ua } -UseBasicParsing -TimeoutSec 60).Content

$keep = @('latin', 'latin-ext')
$map = @{}
$matches = [regex]::Matches($css, '(?s)/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})')
$outBlocks = New-Object System.Collections.Generic.List[string]
foreach ($m in $matches) {
    $subset = $m.Groups[1].Value
    if ($keep -notcontains $subset) { continue }
    $block = $m.Groups[2].Value
    $urlMatch = [regex]::Match($block, 'url\((https://[^)]+\.woff2)\)')
    if (-not $urlMatch.Success) { continue }
    $remote = $urlMatch.Groups[1].Value
    $file = [System.IO.Path]::GetFileName(([Uri]$remote).AbsolutePath)
    $local = Join-Path $vendorDir $file
    if (-not $map.ContainsKey($remote)) {
        if (-not (Test-Path $local) -or (Get-Item $local).Length -eq 0) {
            curl.exe -fsSL --retry 3 -o $local $remote
        }
        $map[$remote] = $file
        Write-Host "downloaded $subset $file"
    }
    $block = $block -replace [regex]::Escape($remote), "geist/$file"
    $outBlocks.Add($block)
}
$header = "/* Geist + Geist Mono - local latin subsets, generated by exe/fetch-fonts.ps1 */`n"
Set-Content -Path (Join-Path $fontsDir 'geist.css') -Value ($header + ($outBlocks -join "`n")) -Encoding UTF8
$total = (Get-ChildItem $vendorDir -File | Measure-Object -Property Length -Sum).Sum
Write-Host "geist.css written, $($map.Count) woff2 files, total bytes: $total"
